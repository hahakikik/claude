function table(widthsPct, rows, opt = {}) {
  const cols = widthsPct.map(p => Math.round(W * p / 100));
  cols[cols.length - 1] = W - cols.slice(0, -1).reduce((a, b) => a + b, 0);
  return new Table({
    width: { size: W, type: WidthType.DXA }, columnWidths: cols,
    rows: rows.map((r, ri) => new TableRow({
      tableHeader: ri === 0,
      children: r.map((c, ci) => new TableCell({
        borders, width: { size: cols[ci], type: WidthType.DXA },
        margins: { top: 50, bottom: 50, left: 90, right: 90 },
        shading: ri === 0 ? { type: ShadingType.CLEAR, fill: HEAD_BG, color: 'auto' }
               : (opt.firstColShade && ci === 0 ? { type: ShadingType.CLEAR, fill: 'F7F9FC', color: 'auto' } : undefined),
        children: String(c).split('\n').map(line => new Paragraph({
          spacing: { after: 0, line: 260 },
          children: runs(line, { size: 17, bold: ri === 0 || (opt.firstColBold && ci === 0) }),
        })),
      })),
    })),
  });
}

// 회색 박스(핵심 요약·방정식)
function box(lines, fill = BOX_BG) {
  return new Table({
    width: { size: W, type: WidthType.DXA }, columnWidths: [W],
    rows: [new TableRow({ children: [new TableCell({
      borders: { top: { style: BorderStyle.SINGLE, size: 8, color: NAVY }, bottom: border, left: border, right: border },
      width: { size: W, type: WidthType.DXA },
      shading: { type: ShadingType.CLEAR, fill, color: 'auto' },
      margins: { top: 100, bottom: 100, left: 160, right: 160 },
      children: lines.map(l => new Paragraph({ spacing: { after: 50, line: 280 }, children: runs(l, { size: 19 }) })),
    })] })],
  });
}
