// **굵게** 표기를 TextRun으로 변환
function runs(text, base = {}) {
  return text.split(/(\*\*[^*]+\*\*)/).filter(Boolean).map(t =>
    t.startsWith('**') ? new TextRun({ ...base, text: t.slice(2, -2), bold: true })
                       : new TextRun({ ...base, text: t }));
}
const P = (t, o = {}) => new Paragraph({ children: runs(t, o.run || {}), spacing: { after: 100, line: 300 }, alignment: AlignmentType.JUSTIFIED, ...o.para });
const H1 = t => new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun(t)], spacing: { before: 240, after: 120 } });
const H2 = t => new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun(t)], spacing: { before: 160, after: 80 } });
const B = t => new Paragraph({ numbering: { reference: 'b', level: 0 }, children: runs(t), spacing: { after: 60, line: 290 } });
const SRC = t => new Paragraph({ children: [new TextRun({ text: t, size: 16, color: GRAY })], spacing: { after: 140 } });
const CAP = t => new Paragraph({ alignment: AlignmentType.CENTER, children: [new TextRun({ text: t, size: 18, bold: true, color: NAVY })], spacing: { after: 140 } });
const IMG = (data, w, h) => new Paragraph({ alignment: AlignmentType.CENTER, spacing: { before: 60, after: 40 },
  children: [new ImageRun({ type: 'png', data, transformation: { width: w, height: h } })] });

const border = { style: BorderStyle.SINGLE, size: 4, color: 'BFBFBF' };
